/**
 * 三底座共享 plan 骨架（差异全部收敛在 profile 字段——设计 §5）：
 * 身份 convert（AGENTS.md + 溯源注释 → config/<identity_file>）/ skills copy / hooks merge / MCP merge / auth 置备。
 * project-file 回退档（D-L2-01 档案值切换）：身份 target = workdir 根 AGENTS.md 薄壳位、skills 带 ds-<id>- 前缀。
 * 虚拟源约定：__mcp__（从 spec.connectors 内存物化）/ __auth__/<f>（从 authSourceDir 取源）——executor actions 物化消费。
 */
import type { BaseProfile, Placement, PlacementPlan } from '../contract'
import type { EmployeeSpec } from '../../installs/spec/types'

/** 溯源注释首行（设计 §3.1 统一；devzero 仅内部标识——品牌 §4） */
export function provenanceComment(id: string, version: string): string {
  return `<!-- generated by devzero from ${id}@${version}/AGENTS.md; do not edit by hand -->\n`
}

/** convert 动作的实际内容变换（溯源注释注入；executor actions 的 convert 分支唯一调用点） */
export function convertInstructions(source: string, spec: EmployeeSpec): string {
  return provenanceComment(spec.id, spec.version) + source
}

export function buildPlan(
  profile: BaseProfile,
  spec: EmployeeSpec,
  opts: { home: string; authSourceDir?: string },
): PlacementPlan {
  const placements: Placement[] = []
  const fallback = profile.identity_anchor === 'project-file'

  placements.push({
    source: 'AGENTS.md',
    target: fallback ? 'AGENTS.md' : `config/${profile.identity_file}`,
    action: 'convert',
  })

  for (const skill of spec.skills) {
    placements.push({
      source: `skills/${skill.name}`,
      target: fallback ? `ds-${spec.id}-${skill.name}` : `config/${profile.skills_dir}/${skill.name}`,
      action: 'copy',
    })
  }

  if (spec.hooksFile) {
    placements.push({ source: spec.hooksFile, target: fallback ? '.qoder/settings.json' : 'config/settings.json', action: 'merge' })
  }

  if (spec.connectors.length > 0) {
    placements.push({ source: '__mcp__', target: fallback ? '.mcp.json' : 'config/.mcp.json', action: 'merge' })
  }

  if (profile.auth.kind !== 'none') {
    for (const f of profile.auth.files) {
      placements.push({ source: `__auth__/${f}`, target: `config/${f}`, action: 'symlink' })
    }
  }

  return { base: profile.id, home: opts.home, employeeId: spec.id, spec, authSourceDir: opts.authSourceDir, placements }
}
